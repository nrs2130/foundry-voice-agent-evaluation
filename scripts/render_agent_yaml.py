"""Render the SIRE voice agent definition into azure.yaml (deploy it with `azd deploy`).

Sources of truth: agent/intents.yaml, agent/instructions.md and sire_eval/agent_spec.py.
Re-run this script after editing them, or add a candidate agent to A/B a model change:

    python scripts/render_agent_yaml.py                                   # production-parity baseline
    python scripts/render_agent_yaml.py --candidate-model gpt-realtime    # + sire-voice-agent-candidate
    azd deploy sire-voice-candidate
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from sire_eval.agent_spec import AGENT_NAME_DEFAULT, FLOWS, render_instructions, tool_definitions  # noqa: E402
from sire_eval.settings import REPO_ROOT  # noqa: E402


class _Literal(str):
    pass


class _Dumper(yaml.SafeDumper):
    pass


_Dumper.add_representer(_Literal, lambda d, s: d.represent_scalar("tag:yaml.org,2002:str", s, style="|"))


def voice_service(agent_name: str, model: str, model_type: str, transcription_model: str) -> dict:
    return {
        "host": "azure.ai.agent",
        "uses": ["foundry-project"],
        "project": "agent",
        "kind": "voice",
        "name": agent_name,
        "description": "SIRE voice command router: intent + entity extraction with directory search tools.",
        "modelType": model_type,
        "model": {"id": model},
        "instructions": _Literal(render_instructions()),
        "structuredInputs": {
            "flow": {
                "description": "Badge dialog state: MAIN_MENU, LOGIN, PARTIAL_CALL, YES_NO or CHOOSE.",
                "defaultValue": "MAIN_MENU",
            },
            "flow_guidance": {
                "description": "Flow-specific guidance, including the option list in the CHOOSE flow.",
                "defaultValue": FLOWS["MAIN_MENU"],
            },
        },
        "audio": {
            "input": {
                "format": {"type": "audio/pcm", "rate": 24000},
                "transcription": {"model": transcription_model, "language": "en-US"},
                "turnDetection": {
                    "type": "azure_semantic_vad",
                    "threshold": 0.5,
                    "prefixPaddingMs": 300,
                    "silenceDurationMs": 750,
                },
            },
        },
        "tools": tool_definitions(),
    }


def build_document(args: argparse.Namespace) -> dict:
    services = {
        "foundry-project": {"host": "azure.ai.project", "endpoint": "${AZURE_AI_PROJECT_ENDPOINT}"},
        "sire-voice": voice_service(args.agent_name, args.model, args.model_type, args.transcription_model),
    }
    if args.candidate_model or args.candidate_transcription_model:
        services["sire-voice-candidate"] = voice_service(
            args.candidate_name,
            args.candidate_model or args.model,
            args.candidate_model_type or args.model_type,
            args.candidate_transcription_model or args.transcription_model,
        )
    return {"name": "sire-voice-eval", "infra": {"provider": "microsoft.foundry"}, "services": services}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--agent-name", default=AGENT_NAME_DEFAULT)
    parser.add_argument("--model", default="gpt-realtime-mini", help="Voice model id (managed) or deployment name (self_deployed).")
    parser.add_argument("--model-type", default="managed", choices=["managed", "self_deployed"])
    parser.add_argument("--transcription-model", default="mai-transcribe", help="Input transcription (STT) model.")
    parser.add_argument("--candidate-name", default=f"{AGENT_NAME_DEFAULT}-candidate",
                        help="Name of the optional candidate agent (service sire-voice-candidate).")
    parser.add_argument("--candidate-model", default=None, help="Render a candidate agent with this voice model.")
    parser.add_argument("--candidate-model-type", default=None, choices=["managed", "self_deployed"])
    parser.add_argument("--candidate-transcription-model", default=None, help="Render a candidate agent with this STT model.")
    parser.add_argument("--output", default=str(REPO_ROOT / "azure.yaml"))
    args = parser.parse_args()

    header = (
        "# yaml-language-server: $schema=https://raw.githubusercontent.com/Azure/azure-dev/main/schemas/v1.0/azure.yaml.json\n"
        "# Generated by scripts/render_agent_yaml.py from agent/intents.yaml, agent/instructions.md and\n"
        "# sire_eval/agent_spec.py. Edit those sources and re-render instead of editing this file by hand.\n\n"
    )
    body = yaml.dump(build_document(args), Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=120)
    Path(args.output).write_text(header + body, encoding="utf-8")
    print(f"Wrote {args.output} (agent={args.agent_name}, model={args.model} [{args.model_type}], stt={args.transcription_model})")
    if args.candidate_model or args.candidate_transcription_model:
        print(f"  + candidate {args.candidate_name}: model={args.candidate_model or args.model}, "
              f"stt={args.candidate_transcription_model or args.transcription_model} -> azd deploy sire-voice-candidate")


if __name__ == "__main__":
    main()
